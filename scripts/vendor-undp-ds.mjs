// Copies the parts of the UNDP Design System this site uses out of
// node_modules/@undp/design-system-assets and into src/assets/vendor/undp-ds,
// as one stylesheet plus the icons it points at.
//
// The client compares the header, footer and links against the design
// system's own Storybook, so those components use the system's compiled CSS
// rather than a redrawing of it. It is copied into the repo instead of loaded
// from a CDN: the published site depends on nothing outside itself at runtime,
// and the version only changes when someone runs this script on purpose.
//
//   npm run vendor:ds
//
// The components are copied whole. From base-minimal.min.css — which also
// restyles body, headings, lists and every link, and would undo the report's
// own typography — only three things are taken: the --undpds-* custom
// properties the components read, the grid and visibility classes the header
// and footer markup use, the animated download icon and the link underline's
// keyframes.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const PKG = dirname(require.resolve('@undp/design-system-assets/package.json'));
const VERSION = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8')).version;
const OUT = 'src/assets/vendor/undp-ds';

const COMPONENTS = [
  'country-site-header',
  'language-switcher',
  'mobile-nav',
  'footer',
];

// Icons the templates point at directly, besides those the CSS asks for.
const MARKUP_IMAGES = ['undp-logo-blue.svg', 'undp-logo-white.svg', 'language.svg', 'back.svg'];

// A base-minimal selector is kept only when every class in it is listed here.
const BASE_CLASSES = new Set([
  // grid, as used by the country site header
  'grid-container', 'fluid', 'grid-x', 'grid-margin-x', 'cell',
  'small-1', 'small-3', 'small-8', 'large-2', 'large-auto', 'shrink', 'align-self-middle',
  // and by the footer
  'medium-5', 'medium-6', 'medium-10', 'medium-offset-1', 'show-large', 'show-small',
  // the download icon of the download card
  'download-animated',
]);

// Animations the page's own rules refer to by name: the underline loop of the
// system's links (Foundation › Typography › Links).
const KEYFRAMES = new Set(['lineLoop-animation', 'lineLoop-animation-rtl']);

/** Top-level blocks of a minified stylesheet: [prelude, body]. */
function blocks(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let depth = 1, k = open + 1;
    while (depth) { if (css[k] === '{') depth++; else if (css[k] === '}') depth--; k++; }
    out.push([css.slice(i, open).trim(), css.slice(open + 1, k - 1)]);
    i = k;
  }
  return out;
}

/** Selectors split on top-level commas only (not the ones inside :not(...)). */
function selectors(prelude) {
  const out = [];
  let depth = 0, cur = '';
  for (const ch of prelude) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && !depth) { out.push(cur); cur = ''; } else cur += ch;
  }
  return [...out, cur].map((s) => s.trim()).filter(Boolean);
}

function keepSelector(sel) {
  const classes = [...sel.matchAll(/\.([\w-]+)/g)].map((m) => m[1]);
  return classes.length > 0 && classes.every((c) => BASE_CLASSES.has(c));
}

function filterRules(css) {
  let out = '';
  for (const [prelude, body] of blocks(css)) {
    if (prelude.startsWith('@media')) {
      const inner = filterRules(body);
      if (inner) out += `${prelude}{${inner}}`;
    } else if (prelude.startsWith('@keyframes')) {
      if (KEYFRAMES.has(prelude.split(/\s+/)[1])) out += `${prelude}{${body}}`;
    } else if (!prelude.startsWith('@')) {
      const kept = selectors(prelude).filter(keepSelector);
      if (kept.length) out += `${kept.join(',')}{${body}}`;
    }
  }
  return out;
}

const base = readFileSync(join(PKG, 'css/base-minimal.min.css'), 'utf8');
const root = blocks(base).find(([p]) => p === ':root');
if (!root) throw new Error('No :root block in base-minimal.min.css');

let css = `/*! UNDP Design System assets ${VERSION} (MIT) — generated by scripts/vendor-undp-ds.mjs, do not edit. */\n`;
css += `/* base-minimal: custom properties */\n:root{${root[1]}}\n`;
css += `/* base-minimal: grid, icon and keyframes subset */\n${filterRules(base)}\n`;
for (const name of COMPONENTS) {
  const file = readFileSync(join(PKG, `css/components/${name}.min.css`), 'utf8')
    .replace(/\/\*![\s\S]*?\*\//, '').trim();
  css += `/* components/${name}.min.css */\n${file}\n`;
}

// The components sit two folders below images/ in the package; the bundle sits
// one below, next to its own images/.
css = css.replace(/url\((['"]?)\.\.\/\.\.\/images\//g, 'url($1../images/');
const images = [...new Set([...css.matchAll(/url\(['"]?\.\.\/images\/([\w.-]+)/g)].map((m) => m[1]))];

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'css'), { recursive: true });
mkdirSync(join(OUT, 'images'), { recursive: true });
writeFileSync(join(OUT, 'css/undp-ds.css'), css);
const files = [...new Set([...images, ...MARKUP_IMAGES])];
for (const img of files) {
  copyFileSync(join(PKG, 'images', img), join(OUT, 'images', img));
}
writeFileSync(join(OUT, 'LICENSE'), readFileSync('scripts/undp-ds-LICENSE.txt', 'utf8'));

console.log(`@undp/design-system-assets ${VERSION}: ${css.length} bytes of CSS, ${files.length} images`);
